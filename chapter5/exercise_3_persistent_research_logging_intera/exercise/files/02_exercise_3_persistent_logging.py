# exercise_3_persistent_logging.py

import datetime
from sqlalchemy import create_engine, Column, Integer, String, Text, DateTime
from sqlalchemy.orm import sessionmaker, declarative_base
import os

# --- 1. Database Setup and Model Definition ---
DATABASE_FILE = "agent_runs.db"
DATABASE_URL = f"sqlite:///{DATABASE_FILE}"
Engine = create_engine(DATABASE_URL)
Base = declarative_base()

class ResearchLog(Base):
    """SQLAlchemy model for logging agent research runs."""
    __tablename__ = 'research_logs'

    id = Column(Integer, primary_key=True, index=True)
    timestamp = Column(DateTime, default=datetime.datetime.utcnow)
    query_topic = Column(String, index=True, nullable=False)
    agent_role = Column(String, nullable=False)
    summary_snippet = Column(Text)

# Create tables in the database (if they don't exist)
Base.metadata.create_all(bind=Engine)

# Create a Session factory
SessionLocal = sessionmaker(autocommit=False, autoflush=False, bind=Engine)

# --- 2. Persistence Logic (Integrated as the final task) ---
def persist_research_log(topic: str, role: str, full_report: str):
    """
    Handles the transactional persistence of the agent's research results.
    """
    db = SessionLocal()
    try:
        # Take the first 500 characters of the report for the summary snippet
        snippet = full_report[:500] + "..." if len(full_report) > 500 else full_report

        new_log = ResearchLog(
            query_topic=topic,
            agent_role=role,
            summary_snippet=snippet
        )

        db.add(new_log)
        # Explicitly commit the transaction
        db.commit()
        print(f"[{datetime.datetime.now().strftime('%H:%M:%S')}] Successfully logged research run for topic: {topic}")

    except Exception as e:
        db.rollback()
        print(f"Database error during logging: {e}")
    finally:
        db.close()

# --- 3. Simulated Agent Execution ---
def simulate_agent_run(topic: str, role: str) -> str:
    """Simulates a full agent research task and integrates the persistence step."""
    print(f"\n--- Starting Agent Run for Topic: {topic} ---")
    
    # Simulated complex research output
    report = f"""
    # Research Report on {topic}
    
    The analysis concludes that {topic} is rapidly transforming the market. Key players 
    are investing heavily in decentralized infrastructure to handle the increased load. 
    The regulatory landscape is struggling to keep pace, creating a temporary arbitrage 
    opportunity for early adopters. This report was generated by the {role}.
    
    [Detailed findings... (This section ensures the snippet logic is tested)]
    """
    
    # Persistence Task Integration: Called after the research is complete
    persist_research_log(topic, role, report.strip())
    
    return report.strip()

# --- 4. Verification Script ---
def verify_logs():
    """Connects and queries the database to verify persistence."""
    db = SessionLocal()
    try:
        print("\n" + "=" * 50)
        print(f"--- Verification: Querying Last 5 Agent Runs from {DATABASE_FILE} ---")
        print("=" * 50)
        
        recent_logs = db.query(ResearchLog).order_by(ResearchLog.timestamp.desc()).limit(5).all()
        
        if not recent_logs:
            print("No logs found.")
            return

        for i, log in enumerate(recent_logs):
            print(f"Log {i+1} (ID: {log.id}):")
            print(f"  Time: {log.timestamp.strftime('%Y-%m-%d %H:%M:%S')}")
            print(f"  Topic: {log.query_topic}")
            print(f"  Role: {log.agent_role}")
            print(f"  Snippet: {log.summary_snippet[:50]}...")
            print("-" * 20)
            
    finally:
        db.close()

# --- Execution ---
if __name__ == "__main__":
    
    # Clean up the database file to ensure a fresh run
    if os.path.exists(DATABASE_FILE):
        os.remove(DATABASE_FILE)
        # The engine still holds a connection to the file just deleted, and
        # SQLite reports "attempt to write a readonly database" if it writes
        # through it. Dispose the pool before reopening.
        Engine.dispose()
    Base.metadata.create_all(bind=Engine)

    # Execute multiple agent runs
    simulate_agent_run(
        topic="Future of Quantum Computing in Finance",
        role="Senior Market Analyst"
    )
    simulate_agent_run(
        topic="Ethical Implications of Large Language Models",
        role="AI Ethics Researcher"
    )
    simulate_agent_run(
        topic="Global Supply Chain Resilience Post-2024",
        role="Logistics Strategist"
    )

    # Verification Step
    verify_logs()

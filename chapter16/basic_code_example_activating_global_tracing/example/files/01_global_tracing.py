import os
import sys
import getpass
from langchain_openai import ChatOpenAI
from langchain_core.prompts import ChatPromptTemplate
from langchain_core.output_parsers import StrOutputParser
from langchain_core.runnables import Runnable

# --- 1. Environment Setup: Critical for LangSmith Tracing ---

def setup_langsmith_and_llm_keys():
    """
    Sets up the required environment variables.
    LangSmith tracing is activated and configured here.
    """

    # 1a. Gateway API Key (Required for the model call we want to trace)
    if not os.environ.get("OPENAI_COMPATIBLE_API_KEY"):
        # Ask only when a person is at the keyboard. A script, a CI job or the
        # live runner has nobody to answer, and must get a message, not a hang.
        answer = getpass.getpass("Enter your API key: ") if sys.stdin.isatty() else ""
        if not answer:
            raise SystemExit("OPENAI_COMPATIBLE_API_KEY is not set: export it and rerun.")
        os.environ["OPENAI_COMPATIBLE_API_KEY"] = answer

    # 1b. LangSmith Tracing Activation (The ON/OFF switch)
    # Defaulted on, because tracing is what this chapter is about. Set it to
    # "false" in the environment to run the chain without a LangSmith account.
    os.environ.setdefault("LANGCHAIN_TRACING_V2", "true")

    # 1c. LangSmith Endpoint URL
    # This specifies the destination server for the trace data.
    os.environ["LANGCHAIN_ENDPOINT"] = "https://api.smith.langchain.com"

    # 1d. LangSmith API Key (Authentication)
    # This key authenticates the application with the LangSmith platform.
    if not os.environ.get("LANGCHAIN_API_KEY"):
        answer = getpass.getpass("Enter your LangSmith API Key: ") if sys.stdin.isatty() else ""
        if answer:
            os.environ["LANGCHAIN_API_KEY"] = answer
        else:
            # No key and no account: the chain still runs, it just sends no trace.
            print("LANGCHAIN_API_KEY is not set: running without tracing.")
            os.environ["LANGCHAIN_TRACING_V2"] = "false"

    # 1e. LangSmith Project Name (Organization)
    # All traces generated by this script will be grouped under this project.
    os.environ["LANGCHAIN_PROJECT"] = "Book8_Ch16_BasicTracingExample"

# Execute the environment setup function
setup_langsmith_and_llm_keys()

# The endpoint, model and key come from the environment: the same listing runs
# against any OpenAI-compatible gateway. Tracing goes to LangSmith when its key
# is set, and stays off when it is not.
BASE_URL = os.environ.get("OPENAI_COMPATIBLE_BASE_URL", "https://openrouter.ai/api/v1")
MODEL = os.environ.get("OPENAI_COMPATIBLE_MODEL", "~deepseek/deepseek-flash-latest")
MODEL_ECONOMY = os.environ.get("OPENAI_COMPATIBLE_MODEL_ECONOMY", MODEL)
OPENAI_COMPATIBLE_API_KEY = os.getenv("OPENAI_COMPATIBLE_API_KEY")

# --- 2. Define the Traceable LCEL Chain ---

# Initialize the LLM component
# The ChatOpenAI class is a Runnable component that interacts with the API.
llm: Runnable = ChatOpenAI(model=MODEL, temperature=0.1,
                           base_url=BASE_URL, api_key=OPENAI_COMPATIBLE_API_KEY)

# Define the structured prompt template
# This defines the input structure and instructs the LLM on its role.
prompt: ChatPromptTemplate = ChatPromptTemplate.from_messages([
    ("system", "You are a concise summarization expert. Summarize the user's topic in exactly two bullet points."),
    ("user", "Topic: {topic}")
])

# Define the output parser
# Ensures the raw string output from the LLM is correctly handled.
parser: StrOutputParser = StrOutputParser()

# Construct the LCEL chain using the pipe operator (|)
# The chain represents the sequence of operations: Input -> Prompt -> LLM -> Parser
summarization_chain: Runnable = prompt | llm | parser

# --- 3. Execute and Generate the Trace ---

project_name = os.environ.get("LANGCHAIN_PROJECT", "N/A")
tracing = os.environ.get("LANGCHAIN_TRACING_V2", "false").lower() in ("true", "1")
print(f"\n--- Starting Chain Execution ---")
print(f"Tracing {'enabled' if tracing else 'disabled'} for project: {project_name}")

# Define the input data dictionary
input_data = {"topic": "The importance of observability in complex AI systems."}

# Invoke the chain. Because the environment variables are set, 
# this single call automatically initiates a root "Run" (trace) 
# and records all sub-steps (Prompt, LLM call, Parser) to LangSmith.
result: str = summarization_chain.invoke(input_data)

print("\n--- Chain Output ---")
print(result)

# LangChain automatically prints a URL to the console pointing to the trace 
# in the configured project, confirming successful data transmission.
print("\nCheck your console output above for the LangSmith URL linking to this specific trace.")

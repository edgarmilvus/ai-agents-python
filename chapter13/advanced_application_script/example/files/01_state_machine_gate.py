import time
from enum import Enum, auto
from typing import Optional
from pydantic import BaseModel, Field

# --- 1. State Management Enums ---
class AgentState(Enum):
    ANALYZING = auto()
    AWAITING_APPROVAL = auto()
    EXECUTING_CRITICAL = auto()
    RETHINKING = auto()
    COMPLETED = auto()
    INTERRUPTED = auto()

class ApprovalStatus(Enum):
    PENDING = "P"
    APPROVED = "A"
    OVERRIDE_REJECT = "R"
    
# --- 2. Structured Agent Output (Proposal) ---
class DeploymentProposal(BaseModel):
    # Enforcing structured output for clear communication to the human
    action_type: str = Field(description="Type of infrastructure change.")
    description: str = Field(description="Detailed explanation of the proposed change.")
    risk_level: str = Field(description="Estimated risk (Low, Medium, High).")
    estimated_downtime_minutes: int
    
# --- 3. Simulated Tools ---
class InfrastructureTool:
    @staticmethod
    def analyze_config():
        """Simulates LLM/Tool analyzing current config and generating a proposal."""
        print("Tool: Analyzing current firewall rules...")
        time.sleep(1)
        # Structured output generated by a simulated LLM call
        return DeploymentProposal(
            action_type="Firewall Rule Update",
            description="Open Port 8080 for new API gateway access.",
            risk_level="Medium",
            estimated_downtime_minutes=0
        )

    @staticmethod
    def execute_deployment(proposal: DeploymentProposal):
        """Simulates the critical execution step (irreversible action)."""
        print(f"\n--- CRITICAL EXECUTION STARTED ---")
        print(f"Executing: {proposal.action_type} - {proposal.description}")
        time.sleep(2)
        print("--- CRITICAL EXECUTION SUCCESSFUL ---")

# --- 4. The Autonomous Agent with Interruption Logic ---
class CIUAgent:
    def __init__(self, initial_goal: str):
        self.goal = initial_goal
        self.state = AgentState.ANALYZING
        self.proposal: Optional[DeploymentProposal] = None
        self.approval_status = ApprovalStatus.PENDING

    def _human_approval_gate(self) -> ApprovalStatus:
        """
        Implements the mandatory human-in-the-loop gate.
        Handles the PAUSE and OVERRIDE/REJECT patterns.
        """
        print("\n[GATE TRIGGERED] Agent requires human approval for critical action.")
        print(f"Proposed Action: {self.proposal.action_type} (Risk: {self.proposal.risk_level})")
        print(f"Details: {self.proposal.description}")
        
        # PAUSE Pattern: The agent blocks execution until valid human input is received
        while True:
            user_input = input("Approve (A), Reject/Override (R), or Explain Agent's Rationale (E)? ").upper()
            
            if user_input == "A":
                print("Human Approved. Proceeding with execution.")
                return ApprovalStatus.APPROVED
            elif user_input == "R":
                print("Human Rejected/Overrode. Agent must re-evaluate.")
                # OVERRIDE Pattern: The human input dictates the next state
                return ApprovalStatus.OVERRIDE_REJECT
            elif user_input == "E":
                # Communication Pattern: Agent explains its current state and reasoning
                print(f"Agent Rationale: My decision is based on the need to meet the goal: '{self.goal}'. The risk is acceptable.")
                # Loop continues, forcing a decision (A or R)
            else:
                print("Invalid input. Please use A, R, or E.")

    def run_workflow(self):
        print(f"Agent Goal: {self.goal}")
        
        while self.state != AgentState.COMPLETED and self.state != AgentState.INTERRUPTED:
            print(f"\n[STATE] Current State: {self.state.name}")
            
            if self.state == AgentState.ANALYZING:
                self.proposal = InfrastructureTool.analyze_config()
                self.state = AgentState.AWAITING_APPROVAL
            
            elif self.state == AgentState.AWAITING_APPROVAL:
                self.approval_status = self._human_approval_gate()
                
                if self.approval_status == ApprovalStatus.APPROVED:
                    self.state = AgentState.EXECUTING_CRITICAL
                elif self.approval_status == ApprovalStatus.OVERRIDE_REJECT:
                    # REDIRECTION Pattern: Flow changes from deployment to rethinking
                    self.state = AgentState.RETHINKING
                else:
                    self.state = AgentState.INTERRUPTED # Safety break
                    
            elif self.state == AgentState.EXECUTING_CRITICAL:
                InfrastructureTool.execute_deployment(self.proposal)
                self.state = AgentState.COMPLETED
                
            elif self.state == AgentState.RETHINKING:
                print("Agent: Human override received. Redirecting plan...")
                time.sleep(1)
                # In a production environment, this would trigger re-analysis or a rollback tool
                print("Agent: Rerouting plan to detailed audit log creation instead of deployment.")
                self.state = AgentState.COMPLETED # End the loop after redirection

        print(f"\n[FINAL STATUS] Agent finished in state: {self.state.name}")

# --- 5. Execution ---
if __name__ == "__main__":
    # Example 1: Successful run (User must input 'A')
    print("--- RUN 1: HUMAN APPROVAL (Expected Input: A) ---")
    agent_success = CIUAgent(initial_goal="Securely expose the new API gateway.")
    agent_success.run_workflow()
    
    print("\n" + "="*50 + "\n")
    
    # Example 2: Interrupted and Redirected run (User must input 'R')
    print("--- RUN 2: HUMAN OVERRIDE AND REDIRECTION (Expected Input: R) ---")
    agent_failure = CIUAgent(initial_goal="Securely expose the new API gateway.")
    agent_failure.run_workflow()
